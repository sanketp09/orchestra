from __future__ import annotations
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field, field_validator, ValidationError
from common.llm_client import get_llm_client
from orchestra.situation import SituationContext
from orchestra.registry import CapabilityRegistry, RegistryCapability


# ============================================================================
# Planner Constants
# ============================================================================

MAX_PLAN_STEPS = 10
MAX_DEPENDENCY_DEPTH = 5
MAX_CANDIDATES_PER_NEED = 5


# ============================================================================
# Custom Exceptions
# ============================================================================

class PlanningError(Exception):
    """Base class for all planning errors."""
    pass


class PlanValidationError(PlanningError):
    """Raised when a proposed plan fails validation checks."""
    def __init__(self, message: str, details: Optional[Dict[str, Any]] = None):
        super().__init__(message)
        self.details = details or {}


# ============================================================================
# Pydantic Planner Schema Contracts
# ============================================================================

class InformationNeed(BaseModel):
    """
    Structured representation of a dynamic query or validation requirement
    derived from the SituationContext.
    """
    need_id: str
    description: str
    priority: str
    source_context: str
    related_facts: list[str] = Field(default_factory=list)
    related_uncertainties: list[str] = Field(default_factory=list)
    related_information_gaps: list[str] = Field(default_factory=list)

    @field_validator("priority")
    @classmethod
    def validate_priority(cls, v: str) -> str:
        allowed = ["high", "medium", "low"]
        if v not in allowed:
            raise ValueError(f"Invalid priority '{v}'. Must be one of {allowed}")
        return v


class InformationNeedsList(BaseModel):
    """Container schema for LLM structured output parsing of needs."""
    needs: List[InformationNeed]


class CapabilityCandidate(BaseModel):
    """
    Evaluated option representing a match between a registry capability
    and an information need.
    """
    capability_id: str
    specialist: str
    description: str
    information_need_id: str
    relevance_score: float = Field(ge=0.0, le=1.0)
    explanation: str


class ScoredCandidateRaw(BaseModel):
    """Raw candidate schema returned from semantic LLM matching."""
    capability_id: str
    information_need_id: str
    relevance_score: float = Field(ge=0.0, le=1.0)
    explanation: str


class ScoredCandidateRawList(BaseModel):
    """Container schema for LLM structured output parsing of scored candidates."""
    candidates: List[ScoredCandidateRaw]


class PlannerResult(BaseModel):
    """Container preserving all evaluated and filtered capability candidates."""
    all_ranked_candidates: List[CapabilityCandidate] = Field(default_factory=list)
    selected_candidates: List[CapabilityCandidate] = Field(default_factory=list)


# ============================================================================
# Phase 3B Planning Schema Contracts
# ============================================================================

class ProposedPlanStep(BaseModel):
    """A proposed step of the plan generated by the LLM."""
    step_id: str
    information_need_id: str
    capability_id: str
    objective: str
    depends_on: list[str] = Field(default_factory=list)
    dependency_reasoning: dict[str, str] = Field(default_factory=dict)
    expected_output: str
    reasoning: str


class ProposedPlan(BaseModel):
    """Plan container proposed by the LLM."""
    steps: list[ProposedPlanStep] = Field(default_factory=list)
    omitted_need_reasons: dict[str, str] = Field(default_factory=dict)


class ValidatedPlanStep(BaseModel):
    """Authoritative, registry-grounded and validated plan step."""
    step_id: str
    information_need_id: str
    capability_id: str
    specialist: str
    endpoint: str
    description: str
    objective: str
    depends_on: list[str] = Field(default_factory=list)
    dependency_reasoning: dict[str, str] = Field(default_factory=dict)
    expected_output: str
    reasoning: str


class ValidatedPlan(BaseModel):
    """Final grounded execution plan ready for execution loops."""
    steps: list[ValidatedPlanStep] = Field(default_factory=list)


# ============================================================================
# Step 1 — Information Need Extraction
# ============================================================================

def extract_information_needs(situation: SituationContext) -> list[InformationNeed]:
    """
    Translates a complex SituationContext objective, facts, gaps, and uncertainties
    into a structured list of InformationNeed requirements using UnifiedLLMClient.
    """
    client = get_llm_client()

    prompt = f"""
Analyze the following procurement situation context and identify the core information needs that must be resolved.
Information needs must specify WHAT needs to be resolved or verified.

CRITICAL RULE: Do NOT mention any specific specialist systems (such as Sentinel, Trustline, Precedent, Arbiter) or specific routing instructions.

Situation Objective: {situation.objective}
Known Facts: {situation.known_facts}
Uncertainties: {situation.uncertainties}
Information Gaps: {situation.information_gaps}

Generate a structured list of InformationNeed items. Each item must have a unique need_id (e.g. 'need_1', 'need_2'), priority (high/medium/low), and related context from the situation.
"""
    raw_res = client.generate_structured(prompt=prompt, schema=InformationNeedsList)
    needs_list = InformationNeedsList.model_validate(raw_res)

    # Enforce unique need_ids and reject duplicate entries
    seen_ids = set()
    validated_needs = []
    for need in needs_list.needs:
        if need.need_id in seen_ids:
            continue
        seen_ids.add(need.need_id)
        validated_needs.append(need)
    return validated_needs


# ============================================================================
# Step 2 — Dynamic Capability Evaluation
# ============================================================================

def evaluate_capabilities(
    needs: list[InformationNeed],
    registry: CapabilityRegistry
) -> list[CapabilityCandidate]:
    """
    Dynamically loads capabilities from the registry and evaluates their relevance
    against the list of extracted InformationNeed requirements.
    """
    if not needs:
        return []

    client = get_llm_client()
    all_caps = registry.list_capabilities()

    # Format the lists for LLM evaluation
    needs_desc = "\n".join([
        f"- ID: {n.need_id} | Description: {n.description} | Priority: {n.priority} | Context: {n.source_context}"
        for n in needs
    ])

    caps_desc = "\n".join([
        f"- ID: {c.id} | Description: {c.description} | Use When: {c.use_when}"
        for c in all_caps
    ])

    prompt = f"""
You are an expert AI orchestrator evaluating how well registered specialist capabilities can resolve a list of current project Information Needs.

Current Project Information Needs:
{needs_desc}

Registered Specialist Capabilities:
{caps_desc}

For each Information Need, evaluate the relevance of EACH registered capability.
Determine if a capability is semantically relevant to solving the information need.
Generate a list of candidate matches. For each match, provide:
- capability_id: MUST exactly match one of the registered capability IDs.
- information_need_id: MUST exactly match one of the Information Need IDs.
- relevance_score: From 0.0 (no relevance) to 1.0 (highly relevant).
- explanation: Brief rationale for why this capability fits this need.

CRITICAL: Do NOT invent or fabricate capability IDs. Every capability_id must exist in the registered list above.
"""
    raw_res = client.generate_structured(prompt=prompt, schema=ScoredCandidateRawList)
    raw_list = ScoredCandidateRawList.model_validate(raw_res)

    # Map of valid needs for validation
    needs_map = {n.need_id: n for n in needs}
    processed_candidates: List[CapabilityCandidate] = []

    for candidate in raw_list.candidates:
        # 1. Reject any candidate whose capability_id does not exist in the registry
        if candidate.capability_id not in registry.capabilities:
            print(f"[Planner] Discarding fabricated capability: {candidate.capability_id}")
            continue

        # 2. Reject any candidate whose information_need_id does not exist in the extracted needs
        if candidate.information_need_id not in needs_map:
            print(f"[Planner] Discarding invalid need reference: {candidate.information_need_id}")
            continue

        # 3. Resolve specialist and capability description from CapabilityRegistry
        registry_cap = registry.get(candidate.capability_id)
        specialist = registry_cap.specialist
        description = registry_cap.description

        # 4. Validate relevance_score range
        score = max(0.0, min(1.0, candidate.relevance_score))

        processed_candidates.append(CapabilityCandidate(
            capability_id=candidate.capability_id,
            specialist=specialist,
            description=description,
            information_need_id=candidate.information_need_id,
            relevance_score=score,
            explanation=candidate.explanation
        ))

    # 5. Deduplicate candidates using (information_need_id, capability_id)
    # Retain the candidate with the highest relevance score
    deduped: Dict[tuple[str, str], CapabilityCandidate] = {}
    for c in processed_candidates:
        key = (c.information_need_id, c.capability_id)
        if key in deduped:
            if c.relevance_score > deduped[key].relevance_score:
                deduped[key] = c
        else:
            deduped[key] = c

    return list(deduped.values())


# ============================================================================
# Step 3 — Deterministic Ranking & Filtering
# ============================================================================

def rank_candidates(
    candidates: list[CapabilityCandidate],
    needs: list[InformationNeed],
    relevance_threshold: float = 0.5
) -> PlannerResult:
    """
    Ranks the list of candidates based on:
    1. relevance_score descending
    2. priority descending (high > medium > low)
    3. capability_id lexicographically ascending
    4. information_need_id lexicographically ascending
    Filters and outputs both complete and threshold-filtered lists.
    """
    priority_map = {"high": 3, "medium": 2, "low": 1}
    need_priorities = {n.need_id: priority_map.get(n.priority, 0) for n in needs}

    def sort_key(c: CapabilityCandidate):
        return (
            -c.relevance_score,
            -need_priorities.get(c.information_need_id, 0),
            c.capability_id,
            c.information_need_id
        )

    all_ranked = sorted(candidates, key=sort_key)
    selected = [c for c in all_ranked if c.relevance_score >= relevance_threshold]

    return PlannerResult(
        all_ranked_candidates=all_ranked,
        selected_candidates=selected
    )


