from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional

class AgentResult(BaseModel):
    agent: str = Field(..., description="Agent name, always 'atlas'")
    task_id: str = Field(..., description="Task identifier matching the request")
    status: str = Field(..., description="Execution status, e.g., 'completed' or 'failed'")
    findings: List[Dict[str, Any]] = Field(default_factory=list, description="Human‑readable findings with optional explanations")
    claims: List[Dict[str, Any]] = Field(default_factory=list, description="Structured claims generated by the capability")
    evidence: List[Dict[str, Any]] = Field(default_factory=list, description="Evidence references stored in Supabase")
    confidence: float = Field(..., description="Overall confidence 0.0‑1.0")
    risks: List[Dict[str, Any]] = Field(default_factory=list, description="Identified risk objects")
    recommended_next_capabilities: List[str] = Field(default_factory=list, description="Capability names ORCHESTRA may invoke next")
    receipt_id: Optional[str] = Field(None, description="ID of the persisted receipt for auditability")
